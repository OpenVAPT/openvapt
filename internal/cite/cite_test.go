var when = time.Date(2026, time.October, 14, 9, 0, 0, 0, time.UTC)

func every(w Work) map[string]string {
	out := map[string]string{"vancouver": w.Vancouver(), "bibmisc": w.BibMisc(), "biblatex": w.BibLaTeX(),
		"page-apa": w.PageAPA(CheckPage("HOST-SSH-001", "SSH Allows Direct Root Login")),
		"page-bib": w.PageBibTeX(ModulePage("F1", "Security Basics")), "report": ReportLine("v0.1.0-alpha.3", when), "credit": Credit}
	for _, f := range Formats {
		s, err := w.Format(f)
		if err != nil {
			panic(err)
		}
		out[f] = s
	}
	return out
}

func TestVersion(t *testing.T) {
	for in, want := range map[string]string{"v0.1.0-alpha.3": "0.1.0-alpha.3", "1.0.0": "1.0.0", "v0.1.0-dev": Unreleased, "": Unreleased, "unknown": Unreleased} {
		if got := Version(in); got != want {
			t.Errorf("Version(%q) = %q, want %q", in, got, want)
		}
	}
	if !strings.Contains(New("v0.1.0-dev", when).APA(), "(Version unreleased build)") {
		t.Error("a build from source must say it is an unreleased build")
	}
}

func TestFormats(t *testing.T) {
	w := New("v0.1.0-alpha.3", when)
	for name, s := range every(w) {
		if s == "" {
			t.Errorf("%s is empty", name)
		}
		if strings.ContainsAny(s, "–—") || strings.Contains(s, "--") {
			t.Errorf("%s contains a dash the writing rules forbid: %q", name, s)
		}
	}
	if _, err := w.Format("nope"); err == nil {
		t.Error("unknown format accepted")
	}
	var v []map[string]any
	if err := json.Unmarshal([]byte(w.CSL()), &v); err != nil || len(v) != 1 {
		t.Fatalf("CSL-JSON invalid: %v", err)
	}
	if w.APA() != "OpenVAPT. (2026). OpenVAPT: An open academic vulnerability assessment tool (Version 0.1.0-alpha.3) [Computer software]. https://github.com/OpenVAPT/openvapt" {
		t.Errorf("APA changed: %s", w.APA())
	}
	if ReportLine("v0.1.0-alpha.3", when) != "Report generated by OpenVAPT v0.1.0-alpha.3 on 2026-10-14." {
		t.Error(ReportLine("v0.1.0-alpha.3", when))
	}
}

// TestNoPersonalNames: the author is always the group author "OpenVAPT".
// Every author field must name exactly OpenVAPT, no person fields may
// appear, and no e-mail address may appear.
func TestNoPersonalNames(t *testing.T) {
	email := regexp.MustCompile(`[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[a-z]{2,}`)
	authorRE := regexp.MustCompile(`(?m)^\s*(author\s*=\s*\{(.*)\},|AU  - (.*)$)`)
	cff, err := os.ReadFile("../../CITATION.cff")
	if err != nil {
		t.Fatal(err)
	}
	for _, w := range []Work{New("v0.1.0-alpha.3", when), New("v0.1.0-dev", when)} {
		texts := every(w)
		texts["CITATION.cff"] = string(cff)
		for name, s := range texts {
			if email.MatchString(s) {
				t.Errorf("%s contains an e-mail address", name)
			}
			for _, bad := range []string{"given-names", "family-names", "\"given\"", "\"family\"", "orcid"} {
				if strings.Contains(s, bad) {
					t.Errorf("%s has a personal name field %q", name, bad)
				}
			}
			for _, m := range authorRE.FindAllStringSubmatch(s, -1) {
				a := m[2] + m[3]
				if a != "{OpenVAPT}" && a != "OpenVAPT" {
					t.Errorf("%s author is %q, want the group author OpenVAPT", name, a)
				}
			}
		}
		var csl []struct {
			Author []map[string]string `json:"author"`
		}
		_ = json.Unmarshal([]byte(w.CSL()), &csl)
		if len(csl[0].Author) != 1 || csl[0].Author[0]["literal"] != Author || len(csl[0].Author[0]) != 1 {
			t.Errorf("CSL author must be only the literal OpenVAPT: %v", csl[0].Author)
		}
		if !strings.Contains(w.BibTeX(), "note         = {"+Made) {
			t.Error("the AI Cybersecurity Engineers credit wording changed from CITING.md")
		}
	}
	if !strings.Contains(string(cff), "authors:\n  - name: \"OpenVAPT\"\n    website: \"https://openvapt.com\"\nrepository-code") {
		t.Error("CITATION.cff must list only the group author OpenVAPT")
	}
}

// TestCitationCFF keeps CITATION.cff valid for GitHub's "Cite this
// repository" button: CFF 1.2.0, no SPDX license key (the licence is not on
// the SPDX list), license-url present, and the same title as every other
// surface.
func TestCitationCFF(t *testing.T) {
	b, err := os.ReadFile("../../CITATION.cff")
	if err != nil {
		t.Fatal(err)
	}
	s := string(b)
	for _, want := range []string{"cff-version: 1.2.0\n", "title: \"" + Title + "\"\n", "type: software\n", "license-url: \"" + RepoURL + "/blob/main/LICENSE\"\n",
		"repository-code: \"" + RepoURL + "\"\n", "url: \"" + SiteURL + "\"\n", "message: "} {
		if !strings.Contains(s, want) {
			t.Errorf("CITATION.cff lacks %q", want)
		}
	}
	if regexp.MustCompile(`(?m)^license:`).MatchString(s) {
		t.Error("CITATION.cff must not have a license key (not an SPDX licence; use license-url)")
	}
	if !regexp.MustCompile(`(?m)^version: "\d+\.\d+\.\d+[^"]*"$`).MatchString(s) || !regexp.MustCompile(`(?m)^date-released: "\d{4}-\d{2}-\d{2}"$`).MatchString(s) {
		t.Error("CITATION.cff needs a quoted version and date-released")
	}
	gen := New("v1.2.3", when).CFF()
	if strings.Contains(gen, "\nlicense:") || !strings.Contains(gen, "license-url:") || !strings.Contains(gen, "version: \"1.2.3\"") {
		t.Errorf("generated CFF invalid:\n%s", gen)
	}
}
