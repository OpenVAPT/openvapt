// TestCitationSameEverywhere: the CLI, every report format, the README and
// CITATION.cff render the same APA and BibTeX core fields, all from
// internal/cite. (The website renders from the same functions; see
// cmd/sitegen/cite_test.go.) The release in CITATION.cff is the version
// the README cites.
func TestCitationSameEverywhere(t *testing.T) {
	cff, err := os.ReadFile("../../CITATION.cff")
	if err != nil {
		t.Fatal(err)
	}
	v := regexp.MustCompile(`(?m)^version: "([^"]+)"`).FindSubmatch(cff)
	d := regexp.MustCompile(`(?m)^date-released: "([^"]+)"`).FindSubmatch(cff)
	if v == nil || d == nil {
		t.Fatal("CITATION.cff lacks version or date-released")
	}
	when, err := time.Parse("2006-01-02", string(d[1]))
	if err != nil {
		t.Fatal(err)
	}
	w := cite.New("v"+string(v[1]), when)
	apa, bib := w.APA(), w.BibTeX()
	if !strings.Contains(string(cff), `title: "`+cite.Title+`"`) {
		t.Error("CITATION.cff title differs from internal/cite")
	}

	readme, err := os.ReadFile("../../README.md")
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(readme), "> "+apa+"\n") {
		t.Errorf("README Cite OpenVAPT section lacks the APA citation for %s:\n%s", v[1], apa)
	}
	if !strings.Contains(string(readme), "```bibtex\n"+bib+"\n```") {
		t.Errorf("README Cite OpenVAPT section lacks the BibTeX for %s:\n%s", v[1], bib)
	}

	old := version.Version
	version.Version = "v" + string(v[1])
	defer func() { version.Version = old }()
	for f, want := range map[string]string{"apa": apa, "bibtex": bib} {
		var out, note bytes.Buffer
		if err := citeTo(&out, &note, []string{"--format", f}, when); err != nil {
			t.Fatal(err)
		}
		if out.String() != want+"\n" {
			t.Errorf("openvapt cite --format %s:\n%s\nwant:\n%s", f, out.String(), want)
		}
		if note.Len() != 0 {
			t.Errorf("a release build must not print the unreleased note: %s", note.String())
		}
	}

	r := &report.Report{Tool: report.Tool{Name: "OpenVAPT", Version: version.Version}, Scan: report.Scan{Started: when},
		Citation: report.NewCitation(version.Version, when)}
	if r.Citation.APA != apa || r.Citation.BibTeX != bib {
		t.Error("report citation differs from internal/cite")
	}
	ref := "Report generated by OpenVAPT v" + string(v[1]) + " on " + string(d[1]) + "."
	if r.Citation.Reference != ref || r.Citation.Credit != cite.Credit {
		t.Errorf("report reference or credit line wrong: %q", r.Citation.Reference)
	}
	js, _ := r.JSON()
	var back struct {
		Citation map[string]string `json:"citation"`
	}
	if err := json.Unmarshal(js, &back); err != nil || back.Citation["apa"] != apa || back.Citation["bibtex"] != bib {
		t.Error("JSON report citation field missing or different")
	}
	sarif, _ := r.SARIF()
	var sv struct {
		Runs []struct {
			Properties struct {
				Citation map[string]string `json:"citation"`
			} `json:"properties"`
		} `json:"runs"`
	}
	if err := json.Unmarshal(sarif, &sv); err != nil || sv.Runs[0].Properties.Citation["apa"] != apa || sv.Runs[0].Properties.Citation["bibtex"] != bib {
		t.Error("SARIF run properties citation missing or different")
	}
	h, err := r.HTML()
	if err != nil {
		t.Fatal(err)
	}
	hs := html.UnescapeString(string(h))
	for _, want := range []string{"How to Cite", apa, bib, ref, cite.Credit} {
		if !strings.Contains(hs, want) {
			t.Errorf("HTML report lacks %q", want)
		}
	}
	md := r.Markdown()
	for _, want := range []string{"## How to Cite", "```bibtex\n" + bib + "\n```", "**APA 7:** OpenVAPT. (" + w.Year + ")", "Version " + string(v[1]), "Licence 1.3"} {
		if !strings.Contains(md, want) {
			t.Errorf("Markdown report lacks %q", want)
		}
	}
	// A report read back from a file never lets its BibTeX close the fence.
	r.Citation.BibTeX = "x\n```\n# injected"
	if !strings.Contains(r.Markdown(), "````bibtex\n") {
		t.Error("Markdown fence can be closed by report content")
	}
}

func TestCiteCommand(t *testing.T) {
	when := time.Date(2026, 10, 14, 0, 0, 0, 0, time.UTC)
	old := version.Version
	version.Version = "v0.1.0-dev"
	defer func() { version.Version = old }()
	var out, note bytes.Buffer
	if err := citeTo(&out, &note, nil, when); err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(out.String(), "(Version unreleased build)") || !strings.Contains(note.String(), "unreleased build") {
		t.Errorf("a build from source must be cited honestly as unreleased: %s %s", out.String(), note.String())
	}
	out.Reset()
	if err := citeTo(&out, &note, []string{"--check", "host-ssh-001", "--format", "bibtex"}, when); err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(out.String(), "@misc{openvapt_host_ssh_001") || !strings.Contains(out.String(), "checks/HOST-SSH-001.html") {
		t.Errorf("check citation wrong: %s", out.String())
	}
	out.Reset()
	if err := citeTo(&out, &note, []string{"--module", "f1"}, when); err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(out.String(), "OpenVAPT Academy") || !strings.Contains(out.String(), "academy/f1.html") {
		t.Errorf("module citation wrong: %s", out.String())
	}
	for _, bad := range [][]string{{"--format", "x"}, {"--check", "NOPE-1"}, {"--module", "zz"}, {"--check", "HOST-SSH-001", "--module", "F1"}, {"extra"}} {
		if err := citeTo(&out, &note, bad, when); err == nil {
			t.Errorf("cite %v should fail", bad)
		}
	}
	var sum bytes.Buffer
	(&report.Report{}).PrintSummary(&sum)
	if !strings.Contains(sum.String(), cite.CLILine) {
		t.Error("scan and demo summary must end with the cite line")
	}
}
